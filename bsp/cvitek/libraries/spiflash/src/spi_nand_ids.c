const struct spi_nand_chip_info *spi_nand_ids_match(const uint8_t *id)
{
    const struct spi_nand_chip_info *info = spi_nand_flash_table;

    /* 与 u-boot spi_nand_get_flash_info 一致：先比前 DEFAULT_ID_LEN 字节，
     * id_len==3 的器件再比第 3 字节，避免前两字节相同的器件误匹配。 */
    for (; info->id_len; info++) {
        if (memcmp(id, info->id, SPI_NAND_DEFAULT_ID_LEN) != 0)
            continue;

        if (info->id_len > SPI_NAND_DEFAULT_ID_LEN) {
            if (memcmp(id, info->id, info->id_len) != 0)
                continue;
        }

        return info;
    }

    return NULL;
}

